#pragma once
#include "xformat.h"

//////////////////////////////////////////////////////////////
/// 媒体封装类
//////////////////////////////////////////////////////////////
class XMux : public XFormat {
public:
  //////////////////////////////////////////////////////////////
  /// 打开封装
  /// with_video / with_audio 控制要创建哪些输出流
  /// 改前问题：不管输入有没有音频/视频都无条件建两条流，
  /// 纯视频源会多出一条 codec_id = AV_CODEC_ID_NONE 的音频流，
  /// avformat_write_header 直接失败（"sample rate not set"）
  //////////////////////////////////////////////////////////////
  static AVFormatContext *Open(const char *url, bool with_video = true,
                               bool with_audio = true);

  //////////////////////////////////////////////////////////////
  /// 写入头部信息
  //////////////////////////////////////////////////////////////
  bool WriteHeader();

  //////////////////////////////////////////////////////////////
  /// 写入pkt
  //////////////////////////////////////////////////////////////
  bool Write(AVPacket *pkt);

  //////////////////////////////////////////////////////////////
  /// 写入尾部信息
  //////////////////////////////////////////////////////////////
  bool WriteEnd();

private:
  // header 未成功写入时 muxer 内部未初始化，不能写帧/trailer
  bool header_written_{false};
};
